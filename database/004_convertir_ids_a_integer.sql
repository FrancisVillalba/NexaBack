-- Ejecutar en NexaDB si las tres tablas existentes todavía tienen Id UUID.
-- Detener el backend mientras se realiza la conversión.
-- Conserva los registros y reconstruye PersonaId/PerfilId con los nuevos números.
-- Los UUID anteriores se sustituyen; cualquier referencia externa a ellos debe actualizarse.
-- Si hay dependencias adicionales, PostgreSQL cancela la transacción sin eliminarlas.
BEGIN;
SET LOCAL lock_timeout = '10s';

LOCK TABLE usuarios.personas, usuarios.perfiles, usuarios.usuarios IN ACCESS EXCLUSIVE MODE;

DO $validar$
BEGIN
    IF (
        SELECT count(*) FROM information_schema.columns
        WHERE table_schema = 'usuarios'
          AND table_name IN ('personas', 'perfiles', 'usuarios')
          AND column_name = 'Id' AND data_type = 'uuid'
    ) <> 3 THEN
        RAISE EXCEPTION 'Se requieren las tres tablas con Id UUID. Si ya son integer, no ejecutar esta conversión.';
    END IF;
END;
$validar$;

ALTER TABLE usuarios.personas ADD COLUMN "IdInt" integer GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE usuarios.perfiles ADD COLUMN "IdInt" integer GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE usuarios.usuarios ADD COLUMN "IdInt" integer GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE usuarios.usuarios ADD COLUMN "PersonaIdInt" integer;
ALTER TABLE usuarios.usuarios ADD COLUMN "PerfilIdInt" integer;

UPDATE usuarios.usuarios u SET "PersonaIdInt" = p."IdInt"
FROM usuarios.personas p WHERE u."PersonaId" = p."Id";
UPDATE usuarios.usuarios u SET "PerfilIdInt" = p."IdInt"
FROM usuarios.perfiles p WHERE u."PerfilId" = p."Id";

ALTER TABLE usuarios.usuarios ALTER COLUMN "PersonaIdInt" SET NOT NULL;
ALTER TABLE usuarios.usuarios ALTER COLUMN "PerfilIdInt" SET NOT NULL;

ALTER TABLE usuarios.usuarios DROP CONSTRAINT "FK_usuarios_personas_PersonaId";
ALTER TABLE usuarios.usuarios DROP CONSTRAINT "FK_usuarios_perfiles_PerfilId";
ALTER TABLE usuarios.usuarios DROP CONSTRAINT "PK_usuarios";
ALTER TABLE usuarios.personas DROP CONSTRAINT "PK_personas";
ALTER TABLE usuarios.perfiles DROP CONSTRAINT "PK_perfiles";

ALTER TABLE usuarios.usuarios DROP COLUMN "PersonaId", DROP COLUMN "PerfilId", DROP COLUMN "Id";
ALTER TABLE usuarios.personas DROP COLUMN "Id";
ALTER TABLE usuarios.perfiles DROP COLUMN "Id";

ALTER TABLE usuarios.personas RENAME COLUMN "IdInt" TO "Id";
ALTER TABLE usuarios.perfiles RENAME COLUMN "IdInt" TO "Id";
ALTER TABLE usuarios.usuarios RENAME COLUMN "IdInt" TO "Id";
ALTER TABLE usuarios.usuarios RENAME COLUMN "PersonaIdInt" TO "PersonaId";
ALTER TABLE usuarios.usuarios RENAME COLUMN "PerfilIdInt" TO "PerfilId";

ALTER SEQUENCE usuarios."personas_IdInt_seq" RENAME TO "personas_Id_seq";
ALTER SEQUENCE usuarios."perfiles_IdInt_seq" RENAME TO "perfiles_Id_seq";
ALTER SEQUENCE usuarios."usuarios_IdInt_seq" RENAME TO "usuarios_Id_seq";

ALTER TABLE usuarios.personas ADD CONSTRAINT "PK_personas" PRIMARY KEY ("Id");
ALTER TABLE usuarios.perfiles ADD CONSTRAINT "PK_perfiles" PRIMARY KEY ("Id");
ALTER TABLE usuarios.usuarios ADD CONSTRAINT "PK_usuarios" PRIMARY KEY ("Id");

CREATE UNIQUE INDEX "IX_usuarios_PersonaId" ON usuarios.usuarios ("PersonaId");
CREATE INDEX "IX_usuarios_PerfilId" ON usuarios.usuarios ("PerfilId");
ALTER TABLE usuarios.usuarios ADD CONSTRAINT "FK_usuarios_personas_PersonaId"
    FOREIGN KEY ("PersonaId") REFERENCES usuarios.personas ("Id") ON DELETE RESTRICT;
ALTER TABLE usuarios.usuarios ADD CONSTRAINT "FK_usuarios_perfiles_PerfilId"
    FOREIGN KEY ("PerfilId") REFERENCES usuarios.perfiles ("Id") ON DELETE RESTRICT;

COMMIT;

-- Los tres Id deben ser integer con is_identity = YES.
SELECT table_name, column_name, data_type, is_identity
FROM information_schema.columns
WHERE table_schema = 'usuarios'
  AND table_name IN ('personas', 'perfiles', 'usuarios')
  AND column_name IN ('Id', 'PersonaId', 'PerfilId')
ORDER BY table_name, column_name;
